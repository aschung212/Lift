#!/usr/bin/env node

/**
 * Production-bundle guard: fails if a dev-only UI surface shipped.
 *
 * Two surfaces exist only for local dev and the CI e2e build (VITE_E2E=true):
 *
 *   1. The dev sign-in bypass (LIFT-1123). AuthScreen renders a "Continue as
 *      Dev" button that calls devSignIn(), which fabricates a
 *      `{ id: 'local-dev' }` session and skips the entire auth gate. It lives
 *      in src/views/DevSignInButton.vue.
 *   2. The Settings dev tools (#1425): Seed XP, Reset Onboarding, Run
 *      Migration, Clear All Data. They live in src/views/DevToolsGroup.vue.
 *      Until #1425 they were an inline group behind a localhost/LAN hostname
 *      test, and the bundled Capacitor app — served from capacitor://localhost
 *      — rendered them on every native install, App Store build included.
 *
 * Both components are lazily imported by their host behind a build-time
 * `import.meta.env.DEV || import.meta.env.VITE_E2E === 'true'` gate, so a
 * normal production build folds the flag to false, tree-shakes the component
 * and never emits its chunk. The only things that could reintroduce one are a
 * misconfigured Vercel env var setting VITE_E2E, or the markup being inlined
 * into its host again (an inline `v-if` ships in every bundle, merely hidden).
 * This script greps the built `dist/` (which CI produces WITHOUT VITE_E2E) for
 * each surface's UI markers and fails the build if any are present.
 *
 * Run against a production build only (e.g. the build-and-test CI job). Running
 * it after `VITE_E2E=true npm run build` is expected to fail.
 *
 * The directory is an optional argument so the deploy-production job can scan
 * `.vercel/output/static` — the artifact `vercel build` actually uploads
 * (LIFT-1169). That build carries the real Vercel project env, so it is the
 * only place this guard can see the misconfiguration described above; and
 * naming the output explicitly avoids assuming `vercel build` leaves `dist/`
 * behind rather than consuming it.
 *
 * `--native` scans the copied web bundle of every synced native platform
 * instead — `ios/App/App/public`, the tree the `.ipa` embeds (LIFT-1454). Every
 * run above inspects a bundle some automated environment produced; the App
 * Store build is the one bundle nothing ever looked at. `npm run cap:build`
 * runs `vite build` LOCALLY and `cap copy` wipes and replaces that tree with the
 * result, so the leak path is `VITE_E2E` being true in the archiving shell —
 * and Vite reads `.env.local` / `.env.*` for every build, so a stray line in an
 * untracked file is enough. That is the LIFT-1435 shape exactly: a variable
 * merely PRESENT in the shell changes what ships, in an artifact Capacitor's own
 * platform `.gitignore` keeps out of git, so it is never diffed and never
 * reviewed. Scanning the copied tree rather than `dist/` is deliberate — the
 * copy is what the archive carries, and the same reasoning makes
 * `guard:native-config` read the EMITTED `capacitor.config.json` rather than the
 * TypeScript it came from.
 *
 * Like its `guard:native-config` sibling, `--native` cannot run in CI: the tree
 * it reads is generated by `cap copy` and gitignored, so a CI checkout has none
 * and every run would fail "never been synced". The halves that CAN be checked
 * without a native toolchain — that each surface stays in its own lazily
 * imported component, and that the web `dist/` is clean — are the structural
 * pins in `prodBundleGuard.test.ts` and the CI run of this same script.
 *
 * `--native --warn` is how the `capacitor:sync:after` hook runs it, for the same
 * reason `guard:native-config` runs `--warn` there: `cap:build` is not the only
 * thing that writes this tree. A bare `npx cap sync` after a `VITE_E2E=true`
 * build copies the leak in and leaves a config `guard:native-config` finds
 * perfectly clean, and that state is gitignored and outlives the session — an
 * archive taken days later inherits it. The hook must never FAIL a sync (both
 * bare sync and live reload are supported workflows), so it reports and steps
 * aside; `cap:build`'s strict run is the gate.
 *
 * Usage:
 *   node scripts/check-no-dev-surface.js [buildDir]        # default: dist
 *   node scripts/check-no-dev-surface.js --native          # every synced native platform
 *   node scripts/check-no-dev-surface.js --native --warn   # report, never fail
 *
 * `buildDir` is resolved from the repo root (not the cwd), so the same
 * invocation works from anywhere in the tree. `--native` takes no directory; it
 * resolves them from the platform table in check-native-release-config.mjs,
 * honouring `CAPACITOR_ROOT_DIR` the way that script and configure-ios.mjs do.
 */

import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { NATIVE_PLATFORMS } from './check-native-release-config.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const args = process.argv.slice(2);

// An unrecognised flag is refused rather than ignored. A mistyped `--natve`
// would otherwise scan `dist/` and print a green line, i.e. vouch for the
// production bundle while standing in for the native one inside `cap:build` —
// a guard answering confidently about a tree it never opened, which is the
// failure this script exists to prevent.
const KNOWN_FLAGS = ['--native', '--warn'];
const unknownFlags = args.filter((arg) => arg.startsWith('-') && !KNOWN_FLAGS.includes(arg));
if (unknownFlags.length > 0) {
  console.error(
    `Error: unknown option${unknownFlags.length > 1 ? 's' : ''} ${unknownFlags.join(', ')}.\n` +
      `Usage: node scripts/check-no-dev-surface.js [buildDir] | --native [--warn]`,
  );
  process.exit(1);
}

const nativeMode = args.includes('--native');
// Only meaningful with --native: the dist/ runs are CI gates and have nothing to
// step aside for.
const warnOnly = nativeMode && args.includes('--warn');
const buildDirArg = args.find((arg) => !arg.startsWith('-'));

// UI markers unique to each surface. We deliberately do NOT grep for
// 'local-dev' / 'dev@localhost': those live in useAuth's devSignIn helper, which
// is part of the composable's returned API and therefore always present in the
// bundle regardless of the flag. A class + a label are what actually render
// each surface, and they are the strings that get tree-shaken out with it.
const SURFACES = [
  {
    name: 'dev sign-in bypass ("Continue as Dev")',
    markers: ['authDevBtn', 'Continue as Dev'],
    hint:
      'The "Continue as Dev" button must never ship to production. This usually ' +
      'means VITE_E2E was set for a production build, or the flag gate in ' +
      'AuthScreen.vue was removed. See LIFT-1123.',
  },
  {
    name: 'Settings dev tools (Seed XP / Clear All Data)',
    markers: ['devToolsGrid', 'Seed 80k XP'],
    hint:
      'The Dev Tools settings group must never ship to production — on the ' +
      'native build it renders for every user. This usually means VITE_E2E was ' +
      'set for a production build, the flag gate in SettingsSheet.vue was ' +
      'removed, or the group was inlined instead of lazily imported from ' +
      'DevToolsGroup.vue. See #1425.',
  },
];

/** Recursively collect every emitted JS file under the build dir (chunks may be lazy). */
function collectJsFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...collectJsFiles(full));
    } else if (entry.isFile() && entry.name.endsWith('.js')) {
      out.push(full);
    }
  }
  return out;
}

/**
 * Scan one built tree, returning `{ scanned, leaks }` — one `leaks` entry per
 * surface that is present, each listing the files carrying it. `base` is stripped
 * from reported paths so the output names the file the way the repo does.
 *
 * Reporting is the caller's, because the two callers mean different things by a
 * finding: the build gates print and fail, the sync hook prints and steps aside.
 * `scanned: 0` is never a pass — reporting a bundle clean having opened no file
 * at all is the one outcome worse than a leak.
 */
function scanBuildDir(dir, base) {
  const jsFiles = collectJsFiles(dir);
  const leaks = [];

  for (const surface of SURFACES) {
    const offenders = [];
    for (const file of jsFiles) {
      const contents = readFileSync(file, 'utf-8');
      const hits = surface.markers.filter((marker) => contents.includes(marker));
      if (hits.length > 0) {
        offenders.push({ file: file.replace(`${base}/`, ''), hits });
      }
    }
    if (offenders.length > 0) leaks.push({ surface, offenders });
  }

  return { scanned: jsFiles.length, leaks };
}

/** Print a scan's findings the way every build gate has printed them since #1425. */
function reportLeaks(leaks) {
  for (const { surface, offenders } of leaks) {
    console.error(`❌ ${surface.name} leaked into the production bundle:`);
    for (const { file, hits } of offenders) {
      console.error(`   ${file} contains: ${hits.join(', ')}`);
    }
    console.error(`\n${surface.hint}\n`);
  }
}

if (nativeMode) {
  // `CAPACITOR_ROOT_DIR` is what the Capacitor CLI sets for its own hooks, and
  // what lets a test point this run at a fixture project — same convention as
  // check-native-release-config.mjs and configure-ios.mjs.
  const nativeRoot = resolve(process.env.CAPACITOR_ROOT_DIR || root);
  const added = NATIVE_PLATFORMS.filter((platform) => existsSync(resolve(nativeRoot, platform.dir)));

  if (warnOnly) {
    // The sync hook: name a leaked surface at the moment the sync copies it in,
    // and never fail — a bare `npx cap sync` and a live-reload sync are both
    // supported. A tree that is absent or empty is not this mode's business
    // either: the copy legitimately does not run when `server.url` is set and
    // `dist/` is missing, and `cap:build`'s strict run is the gate for the rest.
    for (const platform of added) {
      const assetsDir = resolve(nativeRoot, platform.webAssets);
      if (!existsSync(assetsDir)) continue;
      const { leaks } = scanBuildDir(assetsDir, nativeRoot);
      if (leaks.length === 0) continue;
      const names = leaks.map(({ surface }) => surface.name).join('; ');
      console.warn(
        `[guard:dev-surface] ⚠️  ${platform.name} now carries dev-only UI in ` +
          `${platform.webAssets}: ${names}\n` +
          `[guard:dev-surface] ⚠️  This project is NOT archivable as-is — the copied ` +
          `bundle is what the .ipa ships. Unset VITE_E2E (check .env.local too) and ` +
          `re-run \`npm run cap:build\`.`,
      );
    }
    process.exit(0);
  }

  if (added.length === 0) {
    console.log('[guard:dev-surface] no native platform added — nothing to check');
    process.exit(0);
  }

  let failed = false;
  let scanned = 0;
  for (const platform of added) {
    const assetsDir = resolve(nativeRoot, platform.webAssets);
    if (!existsSync(assetsDir)) {
      // Inside `cap:build` this means `cap copy` did not run, so whatever an
      // archive would carry is not what was just built — a green guard here
      // would be vouching for a tree that does not exist.
      console.error(
        `❌ ${platform.name}: ${platform.webAssets} does not exist.\n` +
          `   The web bundle was never copied into the native project, so this guard\n` +
          `   has nothing to inspect. Run \`npm run cap:build\`.`,
      );
      failed = true;
      continue;
    }
    const { scanned: count, leaks } = scanBuildDir(assetsDir, nativeRoot);
    scanned += count;
    if (count === 0) {
      console.error(`Error: no .js files found under ${assetsDir} — is the build complete?`);
      failed = true;
    }
    if (leaks.length > 0) {
      reportLeaks(leaks);
      failed = true;
    }
  }

  if (failed) process.exit(1);

  const platforms = added.map((p) => p.name).join(', ');
  console.log(
    `✅ No dev-only UI in the bundle the native app ships (${SURFACES.length} surfaces, ` +
      `${platforms}, scanned ${scanned} JS files).`,
  );
  process.exit(0);
}

const distDir = resolve(root, buildDirArg || 'dist');

if (!existsSync(distDir)) {
  console.error(
    `Error: ${distDir} not found. Run \`npm run build\` before this guard so ` +
      `there is a production bundle to inspect.`,
  );
  process.exit(1);
}

const { scanned, leaks } = scanBuildDir(distDir, root);

if (scanned === 0) {
  console.error(`Error: no .js files found under ${distDir} — is the build complete?`);
  process.exit(1);
}

if (leaks.length > 0) {
  reportLeaks(leaks);
  process.exit(1);
}

console.log(
  `✅ No dev-only UI in the production bundle (${SURFACES.length} surfaces, ` +
    `scanned ${scanned} JS files).`,
);
